static inline void DrawKeyboardOutlineBox(
        int x1,
        int y1,
        int x2,
        int y2,
        u16 color) {
    glLine(x1, y1, x2, y1, color);
    glLine(x1, y2, x2, y2, color);
    glLine(x1, y1 + 1, x1, y2 - 1, color);
    glLine(x2, y1 + 1, x2, y2 - 1, color);
}

